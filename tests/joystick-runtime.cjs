const fs = require('node:fs');
const assert = require('node:assert/strict');
const { createRequire } = require('node:module');
const path = require('node:path');
const repo = process.env.DREAMLAND_REPO || path.resolve(__dirname, '..');
const sourceRoot = process.env.CONTROLS_SOURCE_ROOT || repo;
const localRequire = createRequire(repo + '/package.json');
const ts = localRequire('typescript');
const React = localRequire('react');
const { JSDOM } = localRequire('jsdom');
const dom = new JSDOM('<html><body><div id="root"></div></body></html>', {url:'https://example.test'});
Object.assign(global, {window:dom.window, document:dom.window.document, HTMLElement:dom.window.HTMLElement, IS_REACT_ACT_ENVIRONMENT:true});
const { createRoot } = localRequire('react-dom/client');
const compiled = ts.transpileModule(fs.readFileSync(sourceRoot + '/src/ui/Joystick.tsx', 'utf8'), {compilerOptions:{module:ts.ModuleKind.CommonJS,jsx:ts.JsxEmit.ReactJSX}}).outputText;
const moduleObject = {exports:{}};
new Function('require','module','exports', compiled)(localRequire, moduleObject, moduleObject.exports);
const {Joystick} = moduleObject.exports;
const values = [];
const root = createRoot(document.getElementById('root'));
React.act(() => root.render(React.createElement(Joystick,{onChange:(x,y)=>values.push([x,y])})));
const stick = document.querySelector('[aria-label^="Movement joystick"]');
let captured = null;
stick.setPointerCapture = id => {captured=id;};
stick.hasPointerCapture = id => captured === id;
stick.releasePointerCapture = id => {if(captured===id) captured=null;};
stick.getBoundingClientRect = () => ({left:0,top:0,width:110,height:110});
const pointer = (type,id,x=90,y=55) => React.act(() => {
 const e=new window.Event(type,{bubbles:true,cancelable:true});
 Object.assign(e,{pointerId:id,clientX:x,clientY:y,pointerType:'touch',button:0});
 stick.dispatchEvent(e);
});
pointer('pointerdown',1);
assert(values.at(-1)[0]>0,'first finger must move');
assert.equal(stick.style.touchAction,'none','Android touch browser gestures are disabled');
assert(Math.hypot(...values.at(-1))<=1.001,'movement magnitude is bounded');
const count=values.length;
pointer('pointerdown',2,20,55);
assert.equal(values.length,count,'second pointer must not steal joystick');
pointer('pointerup',2);
assert(values.at(-1)[0]>0,'second pointer release must not stop owner');
pointer('pointermove',1,55,15);
assert(values.at(-1)[1]>0,'owner must still move after second finger');
pointer('lostpointercapture',1);
assert.deepEqual(values.at(-1),[0,0],'lost capture clears move');
pointer('pointerdown',3);
React.act(()=>window.dispatchEvent(new window.Event('blur')));
assert.deepEqual(values.at(-1),[0,0],'blur clears move');
pointer('pointerdown',4);
Object.defineProperty(document,'hidden',{value:true,configurable:true});
React.act(()=>document.dispatchEvent(new window.Event('visibilitychange')));
assert.deepEqual(values.at(-1),[0,0],'hidden tab clears move');
pointer('pointerdown',5);
pointer('pointercancel',5);
assert.deepEqual(values.at(-1),[0,0],'cancel clears move');
const latest=[];
React.act(()=>root.render(React.createElement(Joystick,{onChange:(x,y)=>latest.push([x,y])})));
pointer('pointerdown',6);
assert(latest.at(-1)[0]>0,'latest callback receives movement');
React.act(()=>root.render(React.createElement(Joystick,{onChange:(x,y)=>latest.push([x,y]),disabled:true})));
assert.deepEqual(latest.at(-1),[0,0],'modal disabling clears active movement');
pointer('pointerdown',7);
assert.deepEqual(latest.at(-1),[0,0],'disabled joystick ignores touches');
React.act(()=>root.render(React.createElement(Joystick,{onChange:(x,y)=>latest.push([x,y]),disabled:false})));
pointer('pointerdown',8);
React.act(()=>root.unmount());
assert.deepEqual(latest.at(-1),[0,0],'unmount clears latest callback');
console.log('PASS: joystick single owner, second pointer release, lost capture, blur, visibility, cancel, fresh callback, unmount');
